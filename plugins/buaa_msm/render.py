# ============================ 通用 ============================


def _open_scene_image(site: Site) -> Image.Image:
    """场景底图是插件自带的本地图片；打不开时用灰底，图照出。"""
    path = SCENE_IMAGE_DIR / site.image
    try:
        return Image.open(path).convert("RGBA")
    except OSError as e:
        logger.warning(f"场景底图打不开，用灰底代替 {path}: {e}")
        return Image.new("RGBA", (800, 600), (220, 220, 220, 255))


def _lerp(a: int, b: int, t: float) -> int:
    return int(a + (b - a) * t)


def _gradient_bg(size: tuple[int, int]) -> Image.Image:
    """浅蓝竖向渐变 + 轻微纹理；纹理用 multiply 轻微压暗，不用 add 增亮"""
    w, h = size
    top = (232, 242, 252)
    mid = (220, 235, 250)
    bot = (210, 228, 248)

    colors = []
    for y in range(h):
        t = y / max(h - 1, 1)
        start, end, tt = (top, mid, t / 0.5) if t < 0.5 else (mid, bot, (t - 0.5) / 0.5)
        colors.append(tuple(_lerp(start[i], end[i], tt) for i in range(3)))
    # 每行同色：先画一列再横向拉伸
    column = Image.new("RGB", (1, h))
    column.putdata(colors)
    img = column.resize((w, h), Image.Resampling.NEAREST)

    noise = Image.effect_noise((w, h), 10).convert("L")
    noise = noise.point(lambda p: 235 + int(p * 20 / 255))
    return ImageChops.multiply(img, Image.merge("RGB", (noise, noise, noise)))


def _rounded_rect_mask(size: tuple[int, int], radius: int) -> Image.Image:
    w, h = size
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, w - 1, h - 1), radius=radius, fill=255
    )
    return mask


def _draw_card(dst: Image.Image, rect: tuple[int, int, int, int]) -> None:
    """卡片：半透明白底 + 圆角，不加阴影"""
    x1, y1, x2, y2 = rect
    w, h = x2 - x1, y2 - y1
    card = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(card, "RGBA").rounded_rectangle(
        (0, 0, w - 1, h - 1),
        radius=18,
        fill=(245, 250, 255, 205),
        outline=(230, 240, 250, 170),
        width=2,
    )
    dst.paste(card, (x1, y1), card)


def _draw_text_with_stroke(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int],
    text: str,
    font: ImageFont.FreeTypeFont,
    fill: ColorRGBA,
    stroke: int = 2,
) -> None:
    x, y = xy
    for dx in (-stroke, 0, stroke):
        for dy in (-stroke, 0, stroke):
            if dx or dy:
                draw.text((x + dx, y + dy), text, font=font, fill=(255, 255, 255, 220))
    draw.text((x, y), text, font=font, fill=fill)


def _text_width(font: ImageFont.FreeTypeFont, text: str) -> int:
    return font.getbbox(text)[2]


def _ellipsize(font: ImageFont.FreeTypeFont, text: str, max_width: int) -> str:
    """按像素宽度裁剪字符串并加省略号，避免右侧唱片列表越界。"""
    if _text_width(font, text) <= max_width:
        return text
    for i in range(max(len(text) - 1, 1), 0, -1):
        candidate = text[:i] + "…"
        if _text_width(font, candidate) <= max_width:
            return candidate
    return "…"


def _wrap_text(font: ImageFont.FreeTypeFont, text: str, max_width: int) -> list[str]:
    """按像素宽度换行：保留原有换行，有空格按词拆，没有空格按字拆"""
    lines: list[str] = []
    for para in text.split("\n"):
        para = para.rstrip()
        if not para or _text_width(font, para) <= max_width:
            lines.append(para)
            continue

        has_space = " " in para
        tokens = para.split(" ") if has_space else list(para)
        cur = ""
        for tok in tokens:
            cand = tok if not cur else (f"{cur} {tok}" if has_space else f"{cur}{tok}")
            if _text_width(font, cand) <= max_width:
                cur = cand
                continue
            if cur:
                lines.append(cur)
                cur = tok
                continue
            # 单个 token 就超宽：从长到短切出放得下的片段
            while tok:
                cut = tok
                while cut and _text_width(font, cut) > max_width:
                    cut = cut[:-1]
                if not cut:
                    break
                lines.append(cut)
                tok = tok[len(cut) :]
        if cur:
            lines.append(cur)
    return lines


# ============================ 图标方块 ============================

_tile_base_cache: dict[int, Image.Image] = {}
# 两张图在不同线程并行渲染，都会写这个缓存
_tile_base_lock = threading.Lock()


def _tile_base(size: int) -> Image.Image:
    with _tile_base_lock:
        if size not in _tile_base_cache:
            img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
            ImageDraw.Draw(img).rounded_rectangle(
                (0, 0, size - 1, size - 1),
                radius=TILE_RADIUS,
                fill=TILE_FILL,
                outline=TILE_STROKE,
                width=2,
            )
            _tile_base_cache[size] = img
        return _tile_base_cache[size].copy()


def _make_tile(
    size: int, icon: Image.Image | None, rarity: int, padding: int
) -> Image.Image:
    """底板 + 图标 + 稀有度描边"""
    tile = _tile_base(size)
    if icon is not None:
        icon = icon.convert("RGBA").resize(
            (size - padding * 2, size - padding * 2), Image.Resampling.LANCZOS
        )
        tile.paste(icon, (padding, padding), icon)
    if rarity:
        ImageDraw.Draw(tile, "RGBA").rounded_rectangle(
            (2, 2, size - 3, size - 3),
            radius=TILE_RADIUS,
            outline=SUPER_RARE_STROKE if rarity == 2 else RARE_STROKE,
            width=4,
        )
    return tile


def _tile_icon(category: str, item_id: int, size: int) -> Image.Image | None:
    path = texture_path(category, item_id)
    if path is None:
        return None
    try:
        return get_icon(path, (size, size))
    except OSError as e:
        logger.warning(f"图标打不开，不画 {path}: {e}")
        return None


def _qty_color(qty: int) -> ColorRGBA:
    if qty == 2:
        return (200, 20, 0, 255)
    if qty > 2:
        return (180, 20, 200, 255)
    return (60, 60, 60, 255)


# ============================ 统计图 ============================


def render_summary(
    data: MsrData, jackets: dict[int, Image.Image], repeated: set[str]
) -> bytes:
    """来访角色卡（含今日唱片）+ 每个场景一张卡：左侧缩略图，右侧「图标方块 + 大数字」网格"""
    padding = 26
    w = 1000

    font_title = get_font(30)
    font_h2 = get_font(22)
    font_num = get_font(28)
    font_text = get_font(16)
    font_small = get_font(14)

    # 唱片按所有场景汇总，最多列 10 张
    record_qty: dict[int, int] = {}
    for summary in data.materials.values():
        for (category, item_id), qty in summary.items():
            if category == "mysekai_music_record":
                record_qty[item_id] = record_qty.get(item_id, 0) + qty
    record_items = sorted(record_qty.items(), key=lambda kv: (-kv[1], kv[0]))[:10]

    visitors = sorted(data.visitors, key=lambda v: v.count, reverse=True)[:6]

    col_count = 5
    cell_h = 54
    min_card_h = 190
    map_cards = [site_id for site_id in HARVEST_SITES if site_id in data.materials]
    items_by_site: dict[int, list[tuple[str, int, int, int]]] = {}
    card_h_by_site: dict[int, int] = {}
    for site_id in map_cards:
        items = [
            (category, item_id, qty, rarity_level(category, item_id))
            for (category, item_id), qty in data.materials[site_id].items()
        ]
        items.sort(key=lambda t: (-t[3], -t[2], t[1]))
        items_by_site[site_id] = items
        rows = (len(items) + col_count - 1) // col_count
        card_h_by_site[site_id] = max(min_card_h, 44 + rows * cell_h + 18)

    record_row_h = 90  # 封面 80px + 间距
    char_row_h = 22
    has_visit_card = bool(visitors or record_items)
    visit_card_h = (
        44 + max(len(visitors) * char_row_h, len(record_items) * record_row_h) + 16
    )

    content_h = 100
    if has_visit_card:
        content_h += visit_card_h + 18
    for site_id in map_cards:
        content_h += card_h_by_site[site_id] + 18

    # 水印在右下角，底部留出它的高度，不压到内容
    margin_x = 18
    margin_y = 14
    wm_lines = _wrap_text(font_small, WATERMARK, min(560, w - margin_x * 2))
    bbox = font_small.getbbox("Ag")
    line_h = (bbox[3] - bbox[1]) + 4
    block_h = line_h * len(wm_lines)
    h = content_h + max(padding, margin_y + block_h + 10)

    bg = _gradient_bg((w, h)).convert("RGBA")
    d = ImageDraw.Draw(bg)
    d.text((padding, 18), "MySekai 资源采集报告", fill=(60, 60, 60), font=font_title)

    y = 100

    # 来访角色卡 + 今日唱片
    if has_visit_card:
        _draw_card(bg, (padding, y, w - padding, y + visit_card_h))
        card_w = w - padding * 2
        left_x = padding + 18
        right_x = padding + int(card_w * 0.56)
        right_max_w = (w - padding - 18) - right_x

        d.text((left_x, y + 12), "今日来访角色", fill=(30, 120, 60), font=font_h2)
        y2 = y + 44
        for visitor in visitors:
            suffix = "（今日已来访）" if visitor.group_id in repeated else ""
            d.text(
                (left_x + 4, y2),
                f"• {visitor.name}：{visitor.count}次 {suffix}".strip(),
                fill=(70, 70, 70),
                font=font_text,
            )
            y2 += char_row_h

        d.text((right_x, y + 12), "今日唱片", fill=(60, 90, 170), font=font_h2)
        y3 = y + 44
        jacket_size = 80
        for record_id, qty in record_items:
            text_offset_x = 0
            jacket = jackets.get(record_id)
            if jacket is not None:
                thumb = jacket.resize(
                    (jacket_size, jacket_size), Image.Resampling.LANCZOS
                ).convert("RGBA")
                thumb.putalpha(_rounded_rect_mask((jacket_size, jacket_size), 6))
                bg.paste(thumb, (right_x, y3), thumb)
                text_offset_x = jacket_size + 8

            # 有封面时文字垂直居中于封面
            text_y = y3 + (jacket_size - 16) // 2 if text_offset_x else y3 + 2
            line = _ellipsize(
                font_text,
                f"• {record_name(record_id)}：{qty}个",
                max(10, right_max_w - 60 - text_offset_x),
            )
            d.text(
                (right_x + text_offset_x, text_y),
                line,
                fill=(70, 70, 70),
                font=font_text,
            )
            if record_id in data.owned_records:
                d.text(
                    (
                        right_x + text_offset_x + _text_width(font_text, line) + 6,
                        text_y + 1,
                    ),
                    "（已获得）",
                    fill=(140, 140, 140),
                    font=font_small,
                )
            y3 += record_row_h

        y += visit_card_h + 18

    # 每个场景一张卡
    card_w = w - padding * 2
    grid_x = padding + 18 + 240
    cell_w = int((padding + card_w - 18 - grid_x) / col_count)
    tile_sz = 40
    tile_pad = 7
    for site_id in map_cards:
        site = HARVEST_SITES[site_id]
        card_h = card_h_by_site[site_id]
        _draw_card(bg, (padding, y, padding + card_w, y + card_h))
        d.text((padding + 18, y + 10), site.name, fill=(120, 80, 150), font=font_h2)

        thumb = (
            _open_scene_image(site)
            .convert("RGB")
            .resize((220, 120), Image.Resampling.LANCZOS)
            .convert("RGBA")
        )
        thumb.putalpha(_rounded_rect_mask((220, 120), 16))
        bg.paste(thumb, (padding + 18, y + 52), thumb)

        grid_y = y + 44
        for idx, (category, item_id, qty, rarity) in enumerate(items_by_site[site_id]):
            cx = grid_x + (idx % col_count) * cell_w
            cy = grid_y + (idx // col_count) * cell_h

            # 唱片优先画封面
            icon = jackets.get(item_id) if category == "mysekai_music_record" else None
            if icon is not None:
                icon = icon.resize((tile_sz - 8, tile_sz - 8), Image.Resampling.LANCZOS)
            else:
                icon = _tile_icon(category, item_id, tile_sz - 8)
            tile = _make_tile(tile_sz, icon, rarity, padding=4)
            bg.paste(tile, (cx + tile_pad, cy + 8), tile)

            num_color = {2: (200, 30, 30, 255), 1: (60, 80, 220, 255)}.get(
                rarity, (70, 70, 70, 255)
            )
            num_x = cx + tile_pad + tile_sz + 8
            num_y = cy + 10
            d.text((num_x, num_y), str(qty), fill=num_color, font=font_num)
            if category == "mysekai_music_record" and item_id in data.owned_records:
                d.text(
                    (num_x, num_y + 30), "已获得", fill=(140, 140, 140), font=font_small
                )

        y += card_h + 18

    y0 = max(0, h - margin_y - block_h)
    for i, line in enumerate(wm_lines):
        x = max(0, w - margin_x - _text_width(font_small, line))
        d.text((x, y0 + i * line_h), line, fill=(155, 155, 155), font=font_small)

    out = io.BytesIO()
    ImageEnhance.Brightness(bg.convert("RGB")).enhance(0.94).save(out, format="PNG")
    return out.getvalue()


# ============================ 位置图 ============================


@dataclass
class _TileDraw:
    x: int
    y: int
    tile: Image.Image
    qty: int
    order: int  # 小图标压在最上，其次超稀有、稀有，同层从上到下、从左到右


def _point_marker(
    overlay: Image.Image,
    d: ImageDraw.ImageDraw,
    px_x: float,
    px_y: float,
    fixture_id: int,
    reward: dict[str, dict[int, int]],
    grid_px: float,
) -> None:
    """点位标记：优先画收获点本体贴图，没有就画圆点"""
    icon_path = harvest_fixture_icon(fixture_id) if fixture_id > 0 else None
    if icon_path is not None:
        # 本体贴图略大于圆点，且要上移对齐采集点
        size = max(30, int(grid_px * 5.0))
        try:
            marker = get_icon(icon_path, (size, size))
        except OSError as e:
            logger.warning(f"点位标记打不开，改画圆点 {icon_path}: {e}")
        else:
            pos = (int(px_x + int(-size * 0.5)), int(px_y + int(-size * 0.78)))
            overlay.paste(marker, pos, marker)
            return

    fill_rgb = ImageColor.getrgb(FIXTURE_COLORS.get(fixture_id, "#000000"))
    rare = any(
        rarity_level(category, item_id)
        for category, items in reward.items()
        for item_id in items
    )
    outline_rgb = (255, 0, 0) if rare else (0, 0, 0)
    r = 6
    d.ellipse(
        (px_x - r, px_y - r, px_x + r, px_y + r),
        fill=(*fill_rgb, 210),
        outline=(*outline_rgb, 255),
        width=2,
    )


def _drop_tiles(px_x: float, px_y: float, reward: dict[str, dict[int, int]]):
    """点位上方的掉落方块。同一点位有素材时，其他掉落缩小挂在素材方块右侧"""
    drops = [
        (category, item_id, qty)
        for category, items in reward.items()
        for item_id, qty in items.items()
        if not (category == "mysekai_material" and item_id in MAP_HIDDEN_MATERIALS)
    ]
    has_material = any(category == "mysekai_material" for category, _, _ in drops)

    def sort_key(drop):
        return (-rarity_level(drop[0], drop[1]), -drop[2], drop[1])

    large = sorted(
        (drop for drop in drops if not has_material or drop[0] == "mysekai_material"),
        key=sort_key,
    )
    small = sorted(
        (drop for drop in drops if has_material and drop[0] != "mysekai_material"),
        key=sort_key,
    )

    large_sz = 34
    small_sz = 24
    large_gap = 3
    small_gap = 2
    calls: list[_TileDraw] = []

    def add(x: int, y: int, drop: tuple[str, int, int], size: int, is_small: bool):
        category, item_id, qty = drop
        icon = _tile_icon(category, item_id, size - 8)
        if icon is None:
            return
        rarity = rarity_level(category, item_id)
        order = y * 10000 + x
        if is_small:
            order += 3_000_000_000
        elif rarity == 2:
            order += 2_000_000_000
        elif rarity == 1:
            order += 1_000_000_000
        tile = _make_tile(size, icon, rarity, padding=3)
        calls.append(_TileDraw(x, y, tile, qty, order))

    total_w = len(large) * large_sz + max(0, len(large) - 1) * large_gap
    start_x = int(px_x - total_w / 2)
    base_y = int(px_y - (large_sz + 16))
    large_xs = []
    for i, drop in enumerate(large):
        x = start_x + i * (large_sz + large_gap)
        add(x, base_y, drop, large_sz, is_small=False)
        large_xs.append(x)

    if small:
        # 挂在最靠近点位中心的那个大方块右侧：右上、右下，再往下排
        anchor_x = (
            min(large_xs, key=lambda x: abs((x + large_sz / 2) - px_x))
            if large_xs
            else start_x
        )
        right_x = int(anchor_x + large_sz - small_sz * 0.62)
        right_bottom_y = int(base_y + large_sz - small_sz * 0.68)
        positions = [
            (right_x, int(base_y - small_sz * 0.32)),
            (right_x, right_bottom_y),
        ]
        extra_x = int(anchor_x + large_sz - small_sz * 0.16)
        extra_y = int(right_bottom_y + small_sz + small_gap)
        for i, drop in enumerate(small):
            if i < 2:
                x, y = positions[i]
            else:
                x, y = extra_x, extra_y + (i - 2) * (small_sz + small_gap)
            add(x, y, drop, small_sz, is_small=True)
    return calls


def _render_site(site: Site, points) -> Image.Image:
    base_img = _open_scene_image(site)
    overlay = Image.new("RGBA", base_img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(overlay, "RGBA")
    qty_font = get_font(14)

    grid_px = site.grid_px
    origin_x = base_img.width / 2 + site.offset_x
    origin_y = base_img.height / 2 + site.offset_y

    def to_xy(loc: tuple[int, int]) -> tuple[float, float]:
        x, y = (loc[1], loc[0]) if site.swap_xy else loc
        return (
            origin_x + site.x_sign * x * grid_px,
            origin_y + site.y_sign * y * grid_px,
        )

    # 出生点
    sx, sy = to_xy((0, 0))
    d.ellipse(
        (sx - 7, sy - 7, sx + 7, sy + 7),
        fill=(255, 80, 170, 255),
        outline=(255, 255, 255, 220),
        width=2,
    )

    calls: list[_TileDraw] = []
    for point in points:
        if not point.reward:
            continue
        px_x, px_y = to_xy(point.location)
        _point_marker(overlay, d, px_x, px_y, point.fixture_id, point.reward, grid_px)
        calls.extend(_drop_tiles(px_x, px_y, point.reward))

    calls.sort(key=lambda c: c.order)
    for c in calls:
        overlay.paste(c.tile, (c.x, c.y), c.tile)
        _draw_text_with_stroke(
            d, (c.x + 2, c.y), str(c.qty), qty_font, fill=_qty_color(c.qty)
        )
    return Image.alpha_composite(base_img, overlay).convert("RGB")


def _stitch(images: list[Image.Image]) -> Image.Image:
    """四张拼成 2×2，不足四张竖排；蓝色边框和分隔线"""
    if len(images) == 1:
        return images[0]

    max_w = max(im.width for im in images)
    max_h = max(im.height for im in images)
    border = 10
    line = 10
    blue = (40, 90, 170)

    if len(images) >= 4:
        dst = Image.new(
            "RGB", (max_w * 2 + border * 2 + line, max_h * 2 + border * 2 + line), blue
        )
        for i, im in enumerate(images[:4]):
            dst.paste(
                im,
                (border + (i % 2) * (max_w + line), border + (i // 2) * (max_h + line)),
            )
        return dst

    total_h = sum(im.height for im in images) + border * 2 + line * (len(images) - 1)
    dst = Image.new("RGB", (max_w + border * 2, total_h), blue)
    cur_y = border
    for im in images:
        dst.paste(im, (border + (max_w - im.width) // 2, cur_y))
        cur_y += im.height + line
    return dst


def render_map(data: MsrData) -> bytes:
    """位置图：底图上画采集点标记和掉落方块，左上角标数量；粉点是出生点"""
    images = [
        _render_site(site, data.maps[site_id])
        for site_id, site in HARVEST_SITES.items()
        if site_id in data.maps
    ]
    stitched = _stitch(images) if images else Image.new("RGB", (1, 1), "white")
    out = io.BytesIO()
    stitched.save(out, format="PNG")
    return out.getvalue()
